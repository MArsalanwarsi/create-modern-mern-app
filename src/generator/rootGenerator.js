import { writeFileTree } from '../utils/fs-helpers.js';
import { sanitizePackageName } from '../utils/naming.js';

export async function generateRoot(targetDir, projectName) {
  const sanitizedName = sanitizePackageName(projectName);

  const rootPkg = {
    name: sanitizedName,
    version: '1.0.0',
    private: true,
    workspaces: ["client", "server"],
    engines: { node: ">=24.16.0" },
    description: `Full-stack MERN application (${sanitizedName})`,
    scripts: {
      "dev": "concurrently -n \"CLIENT,SERVER\" -c \"cyan,green\" \"npm run dev:client\" \"npm run dev:server\"",
      "dev:client": "npm --prefix client run dev",
      "dev:server": "npm --prefix server run dev",
      "lint": "npm --prefix client run lint && npm --prefix server run lint",
      "build:client": "npm --prefix client run build",
      "build:server": "npm --prefix server run build",
      "build": "npm run build:client && npm run build:server",
      "install:all": "npm install"
    },
    devDependencies: {
      "concurrently": "^10.0.6"
    }
  };

  const gitignore = `# Dependencies
node_modules/
.pnp
.pnp.js

# Production build outputs
dist/
build/

# Environment files
.env
.env.local
.env.development.local
.env.test.local
.env.production.local

# Logs
npm-debug.log*
yarn-debug.log*
yarn-error.log*

# OS Files
.DS_Store
Thumbs.db

# Uploads directory
server/uploads/
`;

  const readme = `# ${sanitizedName}

A React + Express workspace generated by create-modern-mern-app.

## Start locally

1. Use Node.js 24.16 or newer and start MongoDB or configure an Atlas database.
2. Set MONGO_URI in server/.env. A unique development JWT_SECRET is already generated.
3. Run npm install at the workspace root if you skipped installation.
4. Run npm run dev and open http://localhost:3000. The API listens on port 5000.
5. Check API health, create an account, then sign out and log back in.

## Application map

- client/src/api/client configures Axios, credentials and the request header.
- client/src/pages contains website, auth and dashboard routes.
- client/src/layout/slices contains the navbar, footer, sidebar and header.
- client/src/components/ui contains editable shadcn/ui primitives.
- server/index.js (or index.ts) starts Express after connecting to MongoDB.
- server/src/routes mounts the API. Controllers and models handle requests and persistence.
- server/src/middlewares/requireToken verifies sessions and requireRole enforces database roles.

## API

All endpoints are under /api. GET /health is public. POST /auth/signup and /auth/login set an HTTP-only session cookie. GET /auth/me returns the current user. POST /auth/logout clears the cookie. GET /users requires an admin role. Write requests need the X-Requested-With header set to mern-client.

## Verify and deploy

Run npm run lint and npm run build from the root. Commit the root package-lock.json and use npm ci on clean checkouts. Serve client/dist with a history fallback and forward /api to Express on the same HTTPS origin. Set NODE_ENV=production, MONGO_URI and a stable JWT_SECRET in the host environment. Start the backend with npm --prefix server start.
`;

  await writeFileTree(targetDir, {
    'package.json': JSON.stringify(rootPkg, null, 2),
    '.gitignore': gitignore,
    'README.md': readme
  });
}
