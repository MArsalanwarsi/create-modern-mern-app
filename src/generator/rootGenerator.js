import { writeFileTree } from '../utils/fs-helpers.js';
import { sanitizePackageName } from '../utils/naming.js';

export async function generateRoot(targetDir, projectName, { auth = true, styling = 'shadcn', backendLang = 'js', serverAddOns = [] } = {}) {
  const sanitizedName = sanitizePackageName(projectName);

  const rootPkg = {
    name: sanitizedName,
    version: '1.0.0',
    private: true,
    workspaces: ["client", "server"],
    engines: { node: ">=24.16.0" },
    description: `Full-stack MERN application (${sanitizedName})`,
    scripts: {
      "dev": "concurrently -n \"CLIENT,SERVER\" -c \"cyan,green\" \"npm run dev:client\" \"npm run dev:server\"",
      "dev:client": "npm --prefix client run dev",
      "dev:server": "npm --prefix server run dev",
      "test": "npm --prefix server test",
      "lint": "npm --prefix client run lint && npm --prefix server run lint",
      "build:client": "npm --prefix client run build",
      "build:server": "npm --prefix server run build",
      "build": "npm run build:client && npm run build:server",
      "install:all": "npm install"
    },
    devDependencies: {
      "concurrently": "^10.0.6"
    }
  };

  const gitignore = `# Dependencies
node_modules/
.pnp
.pnp.js

# Production build outputs
dist/
build/
coverage/
*.tsbuildinfo
*.tgz

# Environment files
.env
.env.*
!.env.example

# Logs
npm-debug.log*
yarn-debug.log*
yarn-error.log*

# OS Files
.DS_Store
Thumbs.db

# Uploads directory
server/uploads/
`;

  const readme = `# ${sanitizedName}

A React + Express workspace generated by create-modern-mern-app.

## Start locally

1. Use Node.js 24.16 or newer and start MongoDB or configure an Atlas database.
2. Set MONGO_URI in server/.env.${auth ? ' A unique development JWT_SECRET is already generated.' : ''}
3. Run npm install at the workspace root if you skipped installation.
4. Run npm run dev and open http://localhost:3000. The API listens on port 5000.
5. ${auth ? 'Check API health, create an account, then sign out and log back in.' : 'Use the landing page to check API health.'}

## Application map

- client/src/api/client configures Axios, credentials and the request header.
- client/src/pages contains the generated pages.
- client/src/layout/slices contains the navbar, footer, sidebar and header.
${styling === 'shadcn' ? '- client/src/components/ui contains editable shadcn/ui primitives.' : '- client/src/index.css contains the base styles.'}
- server/index.${backendLang === 'ts' ? 'ts' : 'js'} starts Express after connecting to MongoDB.
- server/src/routes mounts the API. Controllers and models handle requests and persistence.
${auth ? '- server/src/middlewares/requireToken verifies sessions and requireRole enforces database roles.' : ''}

## API

All endpoints are under /api. GET /health is public.${auth ? ' POST /auth/signup and /auth/login set an HTTP-only session cookie. GET /auth/me returns the current user. POST /auth/logout clears the cookie. GET /users and the /dashboard/members directory require an admin role. Create an account normally and provision its role using a trusted database administration workflow.' : ''} Write requests need the X-Requested-With header set to mern-client.

## Verify and deploy

Run npm test, npm run lint and npm run build from the root. Commit the root package-lock.json and use npm ci on clean checkouts. Serve client/dist with a history fallback and forward /api to Express on the same HTTPS origin. Set NODE_ENV=production, MONGO_URI${auth ? ' and a stable JWT_SECRET' : ''} in the host environment. Start the backend with npm --prefix server start.
${auth ? 'Run the full signup and login integration test by setting TEST_MONGO_URI to a dedicated test MongoDB service before npm test. It creates and removes its own uniquely named database.' : ''}

## Troubleshooting

- After a frontend release, revalidate index.html with Cache-Control: no-cache and cache fingerprinted /assets/ files separately.
- Refreshing a client route returns 404: configure your static host to serve index.html for SPA routes. Route /api to Express before the SPA fallback.
- The API works locally but not after deployment: Vite embeds VITE_API_URL at build time. Rebuild the client after changing it. Never put server secrets in VITE_ variables.
- Atlas times out: check the server host’s outbound IP in the Atlas access list, database user credentials and percent-encoding of special characters in the connection URI.
${auth ? '- Multiple replicas: use LOGIN_LIMIT_STORE=mongo on every API instance, with the same database and JWT_SECRET. Allow creation of the auth_rate_limits TTL index. Set TRUSTED_PROXY_CIDRS only for verified ingress proxies.\n- Login succeeds but the dashboard returns 401: use HTTPS in production and route the frontend and API through one origin for the strict session cookie.' : ''}
${serverAddOns.includes('multer') ? '- Local uploads require persistent disk. Use durable storage for serverless or ephemeral deployments.' : ''}
`;

  await writeFileTree(targetDir, {
    'package.json': JSON.stringify(rootPkg, null, 2),
    '.gitignore': gitignore,
    'README.md': readme
  });
}
